    plant = random.Random(args.seed + 1)
    chosen = plant.sample(range(total), N_DUPLICATES + N_MISSING_ICD + N_MISSING_PID + N_BAD_MONTH + N_ISO_MONTH)
    cuts = [N_DUPLICATES, N_MISSING_ICD, N_MISSING_PID, N_BAD_MONTH, N_ISO_MONTH]
    marks, start = {}, 0
    for kind, size in zip(["duplicate", "missing_icd", "missing_pid", "bad_month", "iso_month"], cuts):
        for i in chosen[start:start + size]:
            marks[i] = kind
        start += size

    patients = Patients(rng)
    os.makedirs(args.out_dir, exist_ok=True)
    for old in glob.glob(os.path.join(args.out_dir, "visits_*")):
        os.remove(old)
    kafka_path = os.path.join(args.out_dir, f"visits_{KAFKA_MONTH[-4:]}-{MONTHS.index(KAFKA_MONTH[:3]) + 1:02d}.jsonl")

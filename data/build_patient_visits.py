    year_file, year_writer, current_year = None, None, None
    written, kafka_count, pending = 0, 0, []  # pending duplicates: [records still to wait, record]

    def emit(rec, ym):
        nonlocal year_file, year_writer, current_year, written, kafka_count
        year = ym // 100
        if year != current_year:
            if year_file:
                year_file.close()
            year_file = io.TextIOWrapper(  # mtime=0 keeps the files byte-for-byte identical on every run
                gzip.GzipFile(os.path.join(args.out_dir, f"visits_{year}.csv.gz"), "wb", compresslevel=6, mtime=0),
                encoding="utf-8", newline="")
            year_writer = csv.writer(year_file)
            year_writer.writerow(FIELDS)
            current_year = year
        year_writer.writerow([rec[k] for k in FIELDS])
        written += 1
        if rec["_kafka"]:
            kafka_file.write(json.dumps({k: rec[k] for k in FIELDS}) + "\n")
            kafka_count += 1


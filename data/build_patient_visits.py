"""Turn the IQVIA NMTA extract into patient-level visit records with synthetic patient identities (Lab 4).

The IQVIA file your instructor shares in Canvas is aggregated: each row counts the visits for one combination of
month, payer, age range, gender, drug, and diagnosis, broken out by specialty, state, and care setting. It has no
patient-level records. This script splits every row into single visits (2,892,144 in all) and gives each visit a
synthetic patient: an ID, a name, a Social Security number, and a street address.

THE PATIENT IDENTITIES ARE SYNTHETIC. They are generated by this script, do not describe any real person, and
exist only so Lab 4 can show how to protect patient identifiers (PHI). Which visits belong to which synthetic
patient is decided by the rules below, not by real patient histories. Social Security numbers use area 666,
which the Social Security Administration never assigns.

How visits become patients
  - Each visit's specialty, state, and care setting are drawn from its row's counts, so every row still adds up.
  - A synthetic patient keeps the same payer, age range, gender, and state. Chronic visits (for example,
    atrial fibrillation on warfarin) usually go to a patient already treated for the same condition in that
    group, so patients build up a history over the months. Acute visits mostly go to new patients.
  - The region comes from the state (U.S. Census regions; Puerto Rico is OTHER), matching the IQVIA file.
  - The YES/NO visit columns are not used until their meaning is confirmed.

Planted data-quality problems for Lab 4 (fixed by the seed, so every student gets the same counts)
      500 exact duplicate visits (a resent record, shortly after the original)
      300 visits missing icd10_code
      200 visits missing patient_id
       50 visits with an unreadable month (UNKNOWN)
      200 visits with the month written as YYYY-MM-DD instead of "Mon YYYY" (fixable, not an error)

Run inside the Spark container from the repository folder (takes a few minutes):
    docker compose exec spark-master python3 data/build_patient_visits.py
Input:  the IQVIA CSV in data/iqvia/ (download it from Canvas; never commit it)
Output (data/raw/visits/):
    visits_2020.csv.gz ... visits_2026.csv.gz   all 2,892,644 records, one file per year
    visits_2025-12.jsonl                         the December 2025 records, one JSON object per line, for Kafka
"""

def find_input(path):
    if path:
        return path
    files = sorted(glob.glob(os.path.join(os.path.dirname(os.path.abspath(__file__)), "iqvia", "*.csv")))
    if len(files) != 1:
        sys.exit("Put the IQVIA CSV file from Canvas in the data/iqvia folder (exactly one .csv file), "
                 f"then run this again. Found {len(files)} .csv files there.")
    return files[0]


def load_rows(path):
    """Read the IQVIA file. Returns the rows sorted by month, plus the column groups used."""
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader)
        col = {name: i for i, name in reversed(list(enumerate(header)))}  # first occurrence wins
        first_spec = 13
        i_region, i_state = col["MIDWEST_Patient Visits"], col["ALABAMA_Patient Visits"]
        i_yes, i_setting = col["YES_Patient Visits"], col["HOSPITAL_Patient Visits"]
        groups = {
            "specialty": (first_spec, i_region),
            "state": (i_state, i_yes),
            "setting": (i_setting, len(header)),
        }
        names = {g: [h.replace("_Patient Visits", "") for h in header[a:b]] for g, (a, b) in groups.items()}
        rows, shared = [], {}
        for n, r in enumerate(reader):
            mon, year = r[0].split()
            # Keep only the nonzero counts, as (column, count) pairs: most visit cells are blank.
            counts = {g: tuple((i, int(float(v))) for i, v in enumerate(r[a:b]) if v and float(v))
                      for g, (a, b) in groups.items()}
            base = tuple(shared.setdefault(v, v) for v in r[:13])  # repeated text is stored once
            rows.append((int(year) * 100 + MONTHS.index(mon) + 1, n, base, counts))
    rows.sort(key=lambda x: (x[0], x[1]))
    return rows, names


def expand(rng, names, counts):
    out = [names[i] for i, c in counts for _ in range(c)]
    rng.shuffle(out)
    return out


class Patients:
    def __init__(self, rng):
        self.rng = rng
        self.people = []          # (patient_id, name, ssn, address)
        self.chronic = {}         # (payer, age, gender, state, icd10_3) -> [patient index]
        self.cohort = {}          # (payer, age, gender, state) -> [patient index]
        self.ssn_numbers = None

    def _new(self, cohort, chronic_key):
        rng = self.rng
        gender = cohort[2]
        first = FEMALE if gender == "FEMALE" else MALE if gender == "MALE" else FEMALE + MALE
        n = len(self.people)
        if self.ssn_numbers is None:  # area 666 is never assigned by the SSA: 99 groups x 9,999 serials
            self.ssn_numbers = rng.sample(range(99 * 9999), 99 * 9999)
        g, s = divmod(self.ssn_numbers[n % len(self.ssn_numbers)], 9999)
        self.people.append((
            f"P{n + 1:07d}",
            f"{rng.choice(first)} {rng.choice(LAST)}",
            f"666-{g + 1:02d}-{s + 1:04d}",
            f"{rng.randint(100, 9899)} {rng.choice(STREETS)} {rng.choice(SUFFIXES)}",
        ))
        self.cohort.setdefault(cohort, []).append(n)
        if chronic_key:
            self.chronic.setdefault(chronic_key, []).append(n)
        return n

    def pick(self, cohort, icd3, chronic):
        rng = self.rng
        if chronic:
            key = cohort + (icd3,)
            pool = self.chronic.get(key)
            if pool and rng.random() < REUSE_CHRONIC:
                return pool[rng.randrange(len(pool))]
            return self._new(cohort, key)
        pool = self.cohort.get(cohort)
        if pool and rng.random() < REUSE_ACUTE:
            return pool[rng.randrange(len(pool))]
        return self._new(cohort, None)


